export function translateErrorMessage(message: string): string {
  const value = message.trim()
  if (messagesVi[value]) return messagesVi[value]
  const count = value.match(/^The report has (\d+) (pages|words|characters); at least (\d+) are required\.$/)
  if (count) {
    const units: Record<string, string> = { pages: 'trang', words: 'từ', characters: 'ký tự' }
    return `Báo cáo có ${count[1]} ${units[count[2]]}; yêu cầu ít nhất ${count[3]} ${units[count[2]]}.`
  }
  const size = value.match(/^The report file must be between 1 and (\d+) bytes\.$/)
  if (size) return `Tệp báo cáo phải có nội dung và không được quá ${size[1]} byte.`
  const sections = value.match(/^Required sections are missing: (.+)\.$/)
  if (sections) return `Báo cáo thiếu các mục bắt buộc: ${sections[1]}.`
  const attendanceReason = value.match(/^An attendance adjustment reason cannot exceed (\d+) characters\.$/)
  if (attendanceReason) return `Lý do điều chỉnh điểm danh không được quá ${attendanceReason[1]} ký tự.`
  const chat = value.match(/^A chat message cannot exceed (\d+) characters\.$/)
  if (chat) return `Tin nhắn không được quá ${chat[1]} ký tự.`
  const closedClass = value.match(/^A completed or archived class cannot (.+)\.$/)
  if (closedClass || value === 'Resources cannot be added to a completed or archived class.') return 'Không thể thực hiện thao tác này vì lớp học đã hoàn thành hoặc lưu trữ.'
  // Unknown business details remain actionable until their translation is added.
  return value
}
